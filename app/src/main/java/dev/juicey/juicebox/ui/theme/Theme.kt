/**
 * Paints the app from the selected palette. Material You follows the wallpaper
 * on Android 12+; the named palettes are static Material 3 schemes.
 */
@Composable
fun JuiceboxTheme(
    themeMode: String = ThemeMode.JUICEBOX,
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val mode = ThemeMode.normalize(themeMode)
    val colorScheme = when (mode) {
        ThemeMode.YOU -> if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        } else {
            if (darkTheme) JuiceboxDarkColors else JuiceboxLightColors
        }
        ThemeMode.VIOLET -> if (darkTheme) VioletDarkColors else VioletLightColors
        ThemeMode.OCEAN -> if (darkTheme) OceanDarkColors else OceanLightColors
        ThemeMode.FOREST -> if (darkTheme) ForestDarkColors else ForestLightColors
        ThemeMode.ROSE -> if (darkTheme) RoseDarkColors else RoseLightColors
        else -> if (darkTheme) JuiceboxDarkColors else JuiceboxLightColors
    }
    MaterialTheme(
        colorScheme = colorScheme,
        typography = JuiceTypography,
        shapes = JuiceShapes,
        content = content,
    )
}
